"""Compatibility payloads for clients that probe common engine interfaces.

Studio is a multi-engine proxy, so a few server-wide discovery routes have no
single owning model. These builders render the Studio catalog in the shapes
llama.cpp, Ollama, LM Studio and OpenAI clients expect. They are pure:
the dataplane owns auth, model selection and any engine forwarding.
"""

from __future__ import annotations

import hashlib
from typing import Any, Iterable, Mapping, Optional

from backend.version import APP_VERSION

# A client may ask for ``name:latest`` against a catalog id without the tag.
_LATEST_SUFFIX = ":latest"


def _model_names(row: Mapping[str, Any]) -> set[str]:
    names = {str(row.get("id") or "").strip().lower()}
    names.add(str(row.get("studio_model_id") or "").strip().lower())
    names.add(str(row.get("display_name") or "").strip().lower())
    names.update(str(alias).strip().lower() for alias in (row.get("aliases") or []))
    return {name for name in names if name}


def find_model(rows: Iterable[Mapping[str, Any]], name: str) -> Optional[Mapping[str, Any]]:
    """Find a catalog row by proxy id, catalog id, display name or alias."""
    wanted = str(name or "").strip().lower()
    if not wanted:
        return None
    candidates = [wanted]
    if wanted.endswith(_LATEST_SUFFIX):
        candidates.append(wanted[: -len(_LATEST_SUFFIX)])
    for row in rows:
        names = _model_names(row)
        if any(candidate in names for candidate in candidates):
            return row
    return None


def openai_model(row: Mapping[str, Any], *, response_id: str = "") -> dict:
    return {
        "id": response_id or str(row.get("id") or ""),
        "object": "model",
        "created": 0,
        "owned_by": str(row.get("engine") or "studio"),
    }


def openai_model_list(rows: Iterable[Mapping[str, Any]]) -> dict:
    data = []
    for row in rows:
        data.append(openai_model(row))
        for alias in row.get("aliases") or []:
            data.append(openai_model(row, response_id=str(alias)))
    return {"object": "list", "data": data}


def _context_length(row: Optional[Mapping[str, Any]]) -> Optional[int]:
    if row is None:
        return None
    value = row.get("context_length")
    if isinstance(value, bool) or not isinstance(value, int) or value <= 0:
        return None
    return value


def _family(row: Mapping[str, Any]) -> str:
    family = str(row.get("model_type") or "").strip()
    return family if family and family.lower() != "unknown" else "studio"


def _capabilities(row: Mapping[str, Any]) -> list[str]:
    block = row.get("capabilities") if isinstance(row.get("capabilities"), Mapping) else {}
    inputs = [str(item).lower() for item in (block.get("in") or [])]
    outputs = [str(item).lower() for item in (block.get("out") or [])]
    capabilities: list[str] = []
    if "embedding" in outputs and "text" not in outputs:
        capabilities.append("embedding")
    else:
        capabilities.append("completion")
    if "image" in inputs:
        capabilities.append("vision")
    if "audio" in inputs:
        capabilities.append("audio")
    return capabilities


def _modified_at(row: Mapping[str, Any]) -> str:
    value = row.get("downloaded_at")
    return str(value) if value else "1970-01-01T00:00:00Z"


def ollama_model(row: Mapping[str, Any]) -> dict:
    model = str(row.get("id") or "")
    family = _family(row)
    return {
        "name": model,
        "model": model,
        "modified_at": _modified_at(row),
        "size": int(row.get("file_size") or 0),
        # Ollama clients display a digest; Studio has a content-derived model
        # identity but no blob digest for aggregation-style listings.
        "digest": hashlib.sha256(model.encode("utf-8")).hexdigest(),
        "details": {
            "parent_model": "",
            "format": str(row.get("format") or "gguf"),
            "family": family,
            "families": [family] if family != "studio" else [],
            "parameter_size": "",
            "quantization_level": str(row.get("quantization") or ""),
        },
    }


def ollama_tags(rows: Iterable[Mapping[str, Any]]) -> dict:
    return {"models": [ollama_model(row) for row in rows]}


def ollama_show(row: Mapping[str, Any]) -> dict:
    model = str(row.get("id") or "")
    family = _family(row)
    context = _context_length(row)
    model_info: dict[str, Any] = {"general.architecture": family}
    parameters = ""
    if context is not None:
        # The family-scoped key is what Ollama's /api/show exposes. Also emit
        # the Modelfile-style num_ctx so clients that prefer the runtime
        # override read the same window.
        model_info[f"{family}.context_length"] = context
        parameters = f"num_ctx {context}"
    return {
        "modelfile": f"# Generated by Studio\nFROM {model}\n",
        "parameters": parameters,
        "template": "",
        "details": ollama_model(row)["details"],
        "model_info": model_info,
        "capabilities": _capabilities(row),
    }


def lmstudio_models(
    rows: Iterable[Mapping[str, Any]], running_ids: Iterable[str] = ()
) -> dict:
    loaded = {str(item) for item in running_ids}
    models = []
    for row in rows:
        model = str(row.get("id") or "")
        family = _family(row)
        capabilities = _capabilities(row)
        if "embedding" in capabilities:
            kind = "embedding"
        elif "vision" in capabilities:
            kind = "vlm"
        else:
            kind = "llm"
        context = _context_length(row)
        entry = {
            "type": kind,
            "key": model,
            "display_name": str(row.get("display_name") or model),
            "publisher": str(row.get("publisher") or "studio"),
            "arch": str(row.get("model_type") or family),
            "compatibility_type": "gguf"
            if str(row.get("format") or "").lower() == "gguf"
            else "safetensors",
            "quantization": str(row.get("quantization") or "unknown"),
            "state": "loaded" if model in loaded else "not-loaded",
            "max_context_length": context,
            "loaded_instances": (
                [
                    {
                        "id": model,
                        "config": {"context_length": context} if context else {},
                    }
                ]
                if model in loaded
                else []
            ),
        }
        models.append(entry)
    return {"models": models}


def llama_props(row: Optional[Mapping[str, Any]]) -> dict:
    """llama.cpp-compatible /props payload for a multi-engine proxy.

    Detection only requires ``default_generation_settings``; the remaining
    fields keep the response useful to clients that read the context window or
    model path. Values Studio does not own (chat template, tokens) stay empty
    rather than inventing engine internals.
    """
    context = _context_length(row)
    model = str(row.get("id") or "") if row else ""
    return {
        "default_generation_settings": {
            "id": 0,
            "n_ctx": context if context is not None else 0,
            "n_predict": -1,
            "n_batch": 2048,
            "n_keep": 0,
            "temperature": 0.8,
            "top_k": 40,
            "top_p": 0.95,
            "min_p": 0.05,
            "repeat_penalty": 1.0,
            "seed": -1,
            "stop": [],
            "stream": True,
        },
        "total_slots": 1,
        "model_path": str(
            (row or {}).get("model_path")
            or (row or {}).get("studio_model_id")
            or model
        ),
        "model_alias": model,
        "chat_template": "",
        "bos_token": "",
        "eos_token": "",
        "build_info": f"studio {APP_VERSION}",
        "is_sleeping": False,
        "studio": {
            "proxy": True,
            "version": APP_VERSION,
            "model": model,
        },
    }


def version_payload() -> dict:
    """Server version payload used by clients that probe ``/version``."""
    return {"version": APP_VERSION, "proxy": "studio"}
