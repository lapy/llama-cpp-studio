"""Idempotent bootstrap for a remote development checkout and its state."""

from __future__ import annotations

import os
import shlex
import stat
import sys
from pathlib import Path
from typing import Any, Optional

from .config import (
    DEFAULT_DATA,
    DEFAULT_REPO,
    DEFAULT_SHARED_MODELS,
    DEFAULT_STATE_HOME,
    DEFAULT_WORKTREES,
    Config,
    new_token,
)
from .errors import CommandError, ConfigError, GuardError
from .gitops import GitRepo
from .journal import Journal, CheckpointStore, new_operation_id, operation_record, utc_now
from .locks import atomic_write_text
from .runtime import run_capture


def _default_uid_gid() -> tuple[str, str]:
    if hasattr(os, "getuid"):
        return str(os.getuid()), str(os.getgid())
    return "1000", "1000"


def _detect_origin() -> str:
    source = Path(__file__).resolve().parent.parent
    result = run_capture(["git", "-C", str(source), "remote", "get-url", "origin"], timeout=10)
    return result.stdout.strip() if result.ok else ""


def _clone(repo_url: str, target: Path, ref: str) -> None:
    target.parent.mkdir(parents=True, exist_ok=True)
    args = ["git", "clone"]
    if ref:
        verify = run_capture(["git", "ls-remote", "--heads", repo_url, ref], timeout=60)
        if verify.ok and verify.stdout.strip():
            args.extend(["--branch", ref])
    args.extend([repo_url, str(target)])
    result = run_capture(args, timeout=1800)
    if not result.ok:
        raise CommandError(
            f"git clone failed: {repo_url}",
            argv=result.argv,
            returncode=result.returncode,
            stdout_tail=result.stdout[-4000:],
            stderr_tail=result.stderr[-4000:],
            timed_out=result.timed_out,
        )
    if ref:
        checkout = run_capture(["git", "-C", str(target), "checkout", ref], timeout=120)
        if not checkout.ok:
            raise CommandError(
                f"could not check out ref {ref}",
                argv=checkout.argv,
                returncode=checkout.returncode,
                stderr_tail=checkout.stderr[-4000:],
            )


def _write_wrapper(path: Path, repo: Path, state_home: Path, extra_args: str = "") -> None:
    body = (
        "#!/bin/sh\n"
        "# Generated by devcontrol bootstrap.\n"
        f"export DEV_CONTROL_HOME={shlex.quote(str(state_home))}\n"
        f"cd {shlex.quote(str(repo))} || exit 1\n"
        f'exec python3 -m devcontrol{(" " + extra_args) if extra_args else ""} "$@"\n'
    )
    atomic_write_text(path, body, mode=0o755)
    try:
        path.chmod(path.stat().st_mode | stat.S_IXUSR | stat.S_IXGRP | stat.S_IXOTH)
    except OSError:
        pass


def bootstrap(
    *,
    state_home: Optional[str | Path] = None,
    repo: Optional[str | Path] = None,
    repo_url: str = "",
    ref: str = "",
    data: Optional[str | Path] = None,
    worktrees: Optional[str | Path] = None,
    shared_models: Optional[str | Path] = None,
    image: str = "",
    backend_port: Optional[int] = None,
    frontend_port: Optional[int] = None,
    proxy_port: Optional[int] = None,
    gpu: Optional[str] = None,
    reset_token: bool = False,
    wrappers: bool = True,
    checkpoint: bool = True,
) -> dict[str, Any]:
    state = Path(state_home or os.getenv("DEV_CONTROL_HOME") or DEFAULT_STATE_HOME).expanduser()
    state = state.resolve(strict=False)
    state.mkdir(parents=True, exist_ok=True)
    try:
        state.chmod(0o700)
    except OSError:
        pass
    config = Config.load(state_home=state, require_initialized=False)
    config.state_home = state
    if repo is not None:
        config.repo = Path(repo).expanduser().resolve(strict=False)
    elif os.getenv("DEV_REPO"):
        config.repo = Path(os.environ["DEV_REPO"]).expanduser().resolve(strict=False)
    else:
        config.repo = DEFAULT_REPO.expanduser().resolve(strict=False)
    if data is not None:
        config.data = Path(data).expanduser().resolve(strict=False)
    elif os.getenv("DEV_DATA"):
        config.data = Path(os.environ["DEV_DATA"]).expanduser().resolve(strict=False)
    else:
        config.data = DEFAULT_DATA.expanduser().resolve(strict=False)
    if worktrees is not None:
        config.worktrees = Path(worktrees).expanduser().resolve(strict=False)
    elif os.getenv("DEV_WORKTREES"):
        config.worktrees = Path(os.environ["DEV_WORKTREES"]).expanduser().resolve(strict=False)
    else:
        config.worktrees = DEFAULT_WORKTREES.expanduser().resolve(strict=False)
    if shared_models is not None:
        config.shared_models = Path(shared_models).expanduser().resolve(strict=False)
    elif os.getenv("DEV_SHARED_MODELS"):
        config.shared_models = (
            Path(os.environ["DEV_SHARED_MODELS"]).expanduser().resolve(strict=False)
        )
    else:
        config.shared_models = DEFAULT_SHARED_MODELS.expanduser().resolve(strict=False)
    if image:
        config.image = image
    if backend_port is not None:
        config.backend_port = backend_port
    if frontend_port is not None:
        config.frontend_port = frontend_port
    if proxy_port is not None:
        config.proxy_port = proxy_port
    if gpu is not None:
        config.gpu = gpu
    default_uid, default_gid = _default_uid_gid()
    if not os.getenv("DEV_UID"):
        config.uid = default_uid
    if not os.getenv("DEV_GID"):
        config.gid = default_gid

    created_token = False
    if reset_token or not config.api_token:
        config.api_token = new_token()
        created_token = True
    if not config.primeui_license:
        config.primeui_license = (os.getenv("VITE_PRIMEUI_LICENSE") or "").strip()

    cloned = False
    if not config.repo.exists():
        source = repo_url.strip() or _detect_origin()
        if not source:
            raise GuardError(
                "checkout does not exist and no --repo-url was supplied; "
                "pass a clone URL or create the checkout first"
            )
        _clone(source, config.repo, ref)
        cloned = True
    else:
        if not (config.repo / ".git").exists():
            raise ConfigError(f"checkout exists but is not a git repository: {config.repo}")
        if ref:
            checkout = run_capture(["git", "-C", str(config.repo), "checkout", ref], timeout=120)
            if not checkout.ok:
                raise GuardError(f"could not check out ref {ref}: {checkout.stderr[-1000:]}")

    config.validate()
    for path, mode in (
        (config.data, 0o700),
        (config.data / "config", 0o700),
        (config.data / "logs", 0o700),
        (config.data / "temp", 0o700),
        (config.data / "models", 0o700),
        (config.data / "home", 0o700),
        (config.data / "hf-cache", 0o700),
        (config.data / "ccache", 0o700),
        (config.worktrees, 0o700),
        (config.state_home / "locks", 0o700),
        (config.state_home / "diagnostics", 0o700),
    ):
        path.mkdir(parents=True, exist_ok=True)
        try:
            path.chmod(mode)
        except OSError:
            pass
    config.shared_models.mkdir(parents=True, exist_ok=True)

    config.save()
    config.assert_initialized()

    wrapper_paths = []
    if wrappers:
        bin_dir = Path.home() / ".local" / "bin"
        try:
            bin_dir.mkdir(parents=True, exist_ok=True)
            _write_wrapper(bin_dir / "agent-dev", config.repo, config.state_home)
            _write_wrapper(bin_dir / "agent-dev-mcp", config.repo, config.state_home, "mcp")
            wrapper_paths = [str(bin_dir / "agent-dev"), str(bin_dir / "agent-dev-mcp")]
        except OSError:
            wrapper_paths = []

    operation_id = new_operation_id()
    started = utc_now()
    journal = Journal(config.journal_path)
    checkpoint_payload = None
    if checkpoint:
        git_repo = GitRepo(config.repo)
        git_repo.ensure()
        existing = CheckpointStore(config.checkpoints_path).latest("main")
        if existing is None:
            checkpoint_payload = git_repo.checkpoint(
                worktree="main", label="bootstrap", operation_id=operation_id
            )
            CheckpointStore(config.checkpoints_path).add(checkpoint_payload)
    revision = GitRepo(config.repo).revision()
    journal.append(
        operation_record(
            operation_id=operation_id,
            action="bootstrap",
            actor=config.actor,
            worktree="main",
            revision_before=None,
            revision_after=revision.label,
            status="succeeded",
            request={"repo": str(config.repo), "ref": ref},
            result={
                "cloned": cloned,
                "token_created": created_token,
                "checkpoint": checkpoint_payload.get("id") if checkpoint_payload else None,
            },
            started_at=started,
        )
    )
    return {
        "ok": True,
        "operation_id": operation_id,
        "revision": revision.label,
        "revision_detail": revision.to_dict(),
        "state_home": str(config.state_home),
        "repo": str(config.repo),
        "data": str(config.data),
        "worktrees": str(config.worktrees),
        "shared_models": str(config.shared_models),
        "ports": {
            "backend": config.backend_port,
            "frontend": config.frontend_port,
            "proxy": config.proxy_port,
        },
        "gpu": config.gpu,
        "token_created": created_token,
        "cloned": cloned,
        "checkpoint": checkpoint_payload,
        "wrappers": wrapper_paths,
        "python": sys.version.split()[0],
    }
